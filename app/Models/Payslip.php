<?php

namespace App\Models;

use App\Traits\BelongsToTenant;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;

class Payslip extends Model
{
    use BelongsToTenant, HasFactory, SoftDeletes;

    public const STATUS_DRAFT = 'DRAFT';
    public const STATUS_APPROVED = 'APPROVED';
    public const STATUS_PAID = 'PAID';
    public const STATUS_CANCELLED = 'CANCELLED';

    public const METHOD_CASH = 'CASH';
    public const METHOD_UPI = 'UPI';
    public const METHOD_BANK_TRANSFER = 'BANK_TRANSFER';
    public const METHOD_CHEQUE = 'CHEQUE';

    protected $fillable = [
        'tenant_id',
        'branch_id',
        'user_id',
        'payslip_number',
        'month',
        'year',
        'pay_period_start',
        'pay_period_end',
        'basic_salary',
        'allowances',
        'deductions',
        'gross_salary',
        'total_deductions',
        'net_salary',
        'working_days',
        'present_days',
        'leaves_taken',
        'late_days',
        'status',
        'payment_method',
        'transaction_reference',
        'paid_at',
        'expense_id',
        'bank_name',
        'account_number',
        'ifsc_code',
        'upi_id',
        'notes',
        'created_by',
    ];

    protected function casts(): array
    {
        return [
            'month' => 'integer',
            'year' => 'integer',
            'pay_period_start' => 'date',
            'pay_period_end' => 'date',
            'basic_salary' => 'decimal:2',
            'gross_salary' => 'decimal:2',
            'total_deductions' => 'decimal:2',
            'net_salary' => 'decimal:2',
            'allowances' => 'array',
            'deductions' => 'array',
            'paid_at' => 'datetime',
            'working_days' => 'integer',
            'present_days' => 'integer',
            'leaves_taken' => 'integer',
            'late_days' => 'integer',
        ];
    }

    public function tenant(): BelongsTo
    {
        return $this->belongsTo(Tenant::class);
    }

    public function branch(): BelongsTo
    {
        return $this->belongsTo(Branch::class);
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function expense(): BelongsTo
    {
        return $this->belongsTo(Expense::class);
    }

    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    public function isDraft(): bool
    {
        return strtoupper((string) $this->status) === self::STATUS_DRAFT;
    }

    public function isApproved(): bool
    {
        return strtoupper((string) $this->status) === self::STATUS_APPROVED;
    }

    public function isPaid(): bool
    {
        return strtoupper((string) $this->status) === self::STATUS_PAID;
    }

    public function isCancelled(): bool
    {
        return strtoupper((string) $this->status) === self::STATUS_CANCELLED;
    }

    /**
     * Formatted Month & Year (e.g. "November 2026")
     */
    public function getFormattedPeriodAttribute(): string
    {
        return date('F Y', mktime(0, 0, 0, $this->month, 1, $this->year));
    }

    /**
     * Official Printable / Web Document URL
     */
    public function getDocumentUrlAttribute(): string
    {
        return route('app.payroll.document', $this->id);
    }

    /**
     * WhatsApp Share link with a clean, professional message
     */
    public function getWhatsAppShareUrlAttribute(): string
    {
        $phone = preg_replace('/[^0-9]/', '', (string) $this->user?->phone);
        if (strlen($phone) === 10) {
            $phone = '91' . $phone;
        }

        $gymName = $this->tenant?->name ?? 'Gym Management';
        $staffName = $this->user?->name ?? 'Staff';
        $period = $this->formatted_period;
        $netPay = '₹' . number_format((float) $this->net_salary, 2);
        $status = $this->isPaid() ? 'Paid' : 'Processed';
        $docUrl = $this->document_url;

        $msg = "Dear {$staffName},\n\nYour salary slip for *{$period}* has been generated by *{$gymName}*.\n\n"
             . "📄 *Payslip No:* {$this->payslip_number}\n"
             . "💰 *Net Salary:* {$netPay}\n"
             . "📌 *Status:* {$status}\n\n"
             . "You can view and download your detailed payslip here:\n👉 {$docUrl}\n\n"
             . "Best regards,\n{$gymName} Management";

        return 'https://api.whatsapp.com/send?phone=' . urlencode($phone) . '&text=' . urlencode($msg);
    }

    /**
     * Convert Net Salary to Indian Currency Words (e.g. "Rupees Twenty-Five Thousand Only")
     */
    public function getNetSalaryInWordsAttribute(): string
    {
        $amount = (float) $this->net_salary;
        if ($amount <= 0) {
            return 'Rupees Zero Only';
        }

        $words = $this->convertNumberToIndianWords((int) floor($amount));
        $paise = (int) round(($amount - floor($amount)) * 100);

        $result = 'Rupees ' . $words;
        if ($paise > 0) {
            $result .= ' and ' . $this->convertNumberToIndianWords($paise) . ' Paise';
        }

        return $result . ' Only';
    }

    /**
     * Indian numbering system conversion helper (Crore, Lakh, Thousand, Hundred)
     */
    protected function convertNumberToIndianWords(int $num): string
    {
        if ($num === 0) {
            return 'Zero';
        }

        $ones = [
            0 => '', 1 => 'One', 2 => 'Two', 3 => 'Three', 4 => 'Four',
            5 => 'Five', 6 => 'Six', 7 => 'Seven', 8 => 'Eight', 9 => 'Nine',
            10 => 'Ten', 11 => 'Eleven', 12 => 'Twelve', 13 => 'Thirteen', 14 => 'Fourteen',
            15 => 'Fifteen', 16 => 'Sixteen', 17 => 'Seventeen', 18 => 'Eighteen', 19 => 'Nineteen'
        ];

        $tens = [
            0 => '', 2 => 'Twenty', 3 => 'Thirty', 4 => 'Forty', 5 => 'Fifty',
            6 => 'Sixty', 7 => 'Seventy', 8 => 'Eighty', 9 => 'Ninety'
        ];

        $crore = floor($num / 10000000);
        $num %= 10000000;

        $lakh = floor($num / 100000);
        $num %= 100000;

        $thousand = floor($num / 1000);
        $num %= 1000;

        $hundred = floor($num / 100);
        $num %= 100;

        $parts = [];

        if ($crore > 0) {
            $parts[] = $this->convertNumberToIndianWords((int) $crore) . ' Crore';
        }
        if ($lakh > 0) {
            $parts[] = $this->convertNumberToIndianWords((int) $lakh) . ' Lakh';
        }
        if ($thousand > 0) {
            $parts[] = $this->convertNumberToIndianWords((int) $thousand) . ' Thousand';
        }
        if ($hundred > 0) {
            $parts[] = $this->convertNumberToIndianWords((int) $hundred) . ' Hundred';
        }

        if ($num > 0) {
            if ($num < 20) {
                $parts[] = $ones[$num];
            } else {
                $t = floor($num / 10);
                $o = $num % 10;
                $parts[] = trim($tens[$t] . ' ' . $ones[$o]);
            }
        }

        return implode(' ', $parts);
    }
}
