                <div>
                    <h2 id="policy-2" class="text-lg font-bold text-white mb-2 scroll-mt-24">2. Information We Collect</h2>
                    <p>We collect information necessary to deliver SaaS gym management and biometric access control services:</p>
                    <ul class="list-disc pl-5 mt-2 space-y-2 text-slate-400">
                        <li><strong>Gym Account Details:</strong> Business name, gym owner name, business email, contact phone number, billing address, and GSTIN (if applicable).</li>
                        <li><strong>Gym Member Information:</strong> Entered by gym operators, including member name, mobile phone number, membership plan, admission date, payment receipts, emergency contact, and profile photos.</li>
                        <li><strong>Access & Attendance Data:</strong> Timestamped entry/exit logs recorded via biometric devices (face recognition, fingerprint scanners), QR scanners, or manual check-ins. We do not store raw physical fingerprint images; only anonymized machine user-IDs and alphanumeric tokens are synced.</li>
                        <li><strong>Technical & Usage Data:</strong> IP address, browser type, operating system, session cookies, and login timestamps to ensure account security and fraud prevention.</li>
                    </ul>
                </div>

                <div>
                    <h2 id="policy-3" class="text-lg font-bold text-white mb-2 scroll-mt-24">3. How We Use Your Information</h2>
                    <p>We process personal and operational data strictly for legitimate business purposes:</p>
                    <ul class="list-disc pl-5 mt-2 space-y-1.5 text-slate-400">
                        <li>To provide, operate, and maintain your gym workspace and member portal.</li>
                        <li>To automate membership expiry notices, fee payment receipts, and class schedules via WhatsApp and SMS.</li>
                        <li>To process subscription billing transactions securely through licensed payment aggregators.</li>
                        <li>To synchronize real-time access permissions with your gym's physical turnstile gates.</li>
                        <li>To provide customer support, troubleshoot hardware issues, and prevent platform abuse.</li>
                    </ul>
                </div>

                <div>
                    <h2 id="policy-4" class="text-lg font-bold text-white mb-2 scroll-mt-24">4. Payment Information & Security</h2>
                    <p>
                        All online payments on GymDeskHub are handled by PCI-DSS compliant, RBI-authorized payment aggregators (such as <strong>Razorpay</strong> and <strong>Cashfree</strong>). GymDeskHub does not collect, record, or store sensitive credit card numbers, CVV codes, or net banking passwords. All payment transactions are encrypted using end-to-end 256-bit SSL encryption.
                    </p>
